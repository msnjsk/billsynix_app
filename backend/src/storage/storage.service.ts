import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { Inject, Injectable } from '@nestjs/common';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { ENV } from '../config/config.module.js';
import type { Env } from '../config/env.js';

/** How a stored object is handed to a client. */
export type StoredObject =
  | { kind: 'bytes'; body: Buffer; contentType: string }
  | { kind: 'redirect'; url: string };

const KEY = /^[a-z0-9][a-z0-9/._-]{0,255}$/;

/**
 * Object storage for uploaded files (product photos now; documents later).
 * `local` keeps files on disk — development, tests, single-server installs.
 * `s3` talks to any S3-compatible store (AWS S3, Cloudflare R2, MinIO); reads are short-lived
 * pre-signed URLs, so the bucket stays private.
 */
@Injectable()
export class StorageService {
  private readonly s3?: S3Client;
  private readonly root: string;

  constructor(@Inject(ENV) private readonly env: Env) {
    this.root = resolve(env.STORAGE_LOCAL_DIR);
    if (env.STORAGE_DRIVER === 's3') {
      this.s3 = new S3Client({
        region: env.OBJECT_STORAGE_REGION,
        ...(env.OBJECT_STORAGE_ENDPOINT
          ? { endpoint: env.OBJECT_STORAGE_ENDPOINT, forcePathStyle: true }
          : {}),
        credentials: {
          accessKeyId: env.OBJECT_STORAGE_ACCESS_KEY ?? '',
          secretAccessKey: env.OBJECT_STORAGE_SECRET_KEY ?? '',
        },
      });
    }
  }

  /** Keys are generated by the API, never taken from clients; this is a last guard. */
  private check(key: string) {
    if (!KEY.test(key) || key.includes('..'))
      throw new Error(`Invalid storage key: ${key}`);
  }

  private localPath(key: string) {
    const p = resolve(this.root, key);
    if (!p.startsWith(this.root + sep)) throw new Error('Key escapes root');
    return p;
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    this.check(key);
    if (this.s3) {
      await this.s3.send(
        new PutObjectCommand({
          Bucket: this.env.OBJECT_STORAGE_BUCKET,
          Key: key,
          Body: body,
          ContentType: contentType,
        }),
      );
      return;
    }
    const p = this.localPath(key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, body);
  }

  /** null when the object doesn't exist (local driver; S3 URLs are signed without a lookup). */
  async get(key: string, contentType: string): Promise<StoredObject | null> {
    this.check(key);
    if (this.s3) {
      const url = await getSignedUrl(
        this.s3,
        new GetObjectCommand({
          Bucket: this.env.OBJECT_STORAGE_BUCKET,
          Key: key,
          ResponseContentType: contentType,
        }),
        { expiresIn: 300 },
      );
      return { kind: 'redirect', url };
    }
    try {
      return {
        kind: 'bytes',
        body: await readFile(this.localPath(key)),
        contentType,
      };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    this.check(key);
    if (this.s3) {
      await this.s3.send(
        new DeleteObjectCommand({
          Bucket: this.env.OBJECT_STORAGE_BUCKET,
          Key: key,
        }),
      );
      return;
    }
    await rm(this.localPath(key), { force: true });
  }
}
